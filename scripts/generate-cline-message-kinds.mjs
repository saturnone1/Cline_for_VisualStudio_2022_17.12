import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
const contract = JSON.parse(fs.readFileSync(path.join(root, "contracts", "cline-message-kinds.json"), "utf8"))
const output = `// Generated by scripts/generate-cline-message-kinds.mjs. Do not edit.\n` +
	`export const CLINE_ASK_KIND_MAP = ${JSON.stringify(contract.ask, null, "\t")} as const\n\n` +
	`export const CLINE_SAY_KIND_MAP = ${JSON.stringify(contract.say, null, "\t")} as const\n`
const targets = [
	path.join(root, "src", "shared", "protoConversions", "generated", "clineMessageKinds.ts"),
	path.join(root, "src", "sidecar", "src", "application", "dto", "generated", "ClineMessageKinds.ts"),
]
const check = process.argv.includes("--check")
let drift = false
for (const target of targets) {
	if (check) {
		if (!fs.existsSync(target) || fs.readFileSync(target, "utf8") !== output) {
			console.error(`Generated Cline message kinds are stale: ${path.relative(root, target)}`)
			drift = true
		}
		continue
	}
	fs.mkdirSync(path.dirname(target), { recursive: true })
	fs.writeFileSync(target, output, "utf8")
}
if (drift) process.exit(1)
if (!check) console.log(`Generated Cline message kinds for ${targets.length} runtimes.`)
