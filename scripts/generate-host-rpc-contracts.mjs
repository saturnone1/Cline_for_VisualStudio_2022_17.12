import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
const manifest = JSON.parse(fs.readFileSync(path.join(root, "contracts", "host-rpc.json"), "utf8"))
validate(manifest)

const outputs = new Map([
	[path.join(root, "src", "sidecar", "src", "application", "dto", "generated", "HostRpcContract.ts"), renderTypeScript(manifest)],
	[path.join(root, "src", "extension", "Host", "Generated", "HostRpcContract.cs"), renderCSharp(manifest)],
	[path.join(root, "contracts", "generated", "host-rpc-fixtures.json"), `${JSON.stringify(manifest, null, 2)}\n`],
])

const check = process.argv.includes("--check")
let stale = false
for (const [filePath, content] of outputs) {
	if (check) {
		if (!fs.existsSync(filePath) || fs.readFileSync(filePath, "utf8") !== content) {
			console.error(`Generated Host RPC contract is stale: ${path.relative(root, filePath)}`)
			stale = true
		}
		continue
	}
	fs.mkdirSync(path.dirname(filePath), { recursive: true })
	fs.writeFileSync(filePath, content)
}
if (stale) process.exit(1)

function validate(value) {
	if (value.version !== 1 || !Array.isArray(value.methods) || value.methods.length === 0) throw new Error("Invalid Host RPC manifest.")
	const ids = new Set(), names = new Set()
	for (const method of value.methods) {
		if (!/^[A-Z][A-Za-z0-9]+$/.test(method.id) || typeof method.name !== "string" || typeof method.adapter !== "string") throw new Error(`Invalid Host RPC method: ${JSON.stringify(method)}`)
		if (ids.has(method.id) || names.has(method.name)) throw new Error(`Duplicate Host RPC method: ${method.id}`)
		ids.add(method.id); names.add(method.name)
	}
}

function renderTypeScript(value) {
	const entries = value.methods.map((method) => `\t${method.id}: ${JSON.stringify(method.name)},`).join("\n")
	return `// Generated by scripts/generate-host-rpc-contracts.mjs. Do not edit.\nexport const HOST_RPC_PROTOCOL_VERSION = ${value.version} as const\nexport const HostRpcMethod = {\n${entries}\n} as const\nexport type HostRpcMethodName = (typeof HostRpcMethod)[keyof typeof HostRpcMethod]\nexport const HOST_RPC_METHODS = Object.values(HostRpcMethod)\n`
}

function renderCSharp(value) {
	const constants = value.methods.map((method) => `        public const string ${method.id} = ${JSON.stringify(method.name)};`).join("\n")
	const all = value.methods.map((method) => `            ${method.id},`).join("\n")
	return `// Generated by scripts/generate-host-rpc-contracts.mjs. Do not edit.\nusing System.Collections.Generic;\n\nnamespace VsClineAgent.Host.Generated\n{\n    internal static class HostRpcContract\n    {\n        public const int ProtocolVersion = ${value.version};\n${constants}\n\n        public static readonly IReadOnlyCollection<string> All = new[]\n        {\n${all}\n        };\n    }\n}\n`
}
